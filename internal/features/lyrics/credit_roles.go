func makeCreditFields(groups []string) map[string]string {
	fields := make(map[string]string)
	for _, group := range groups {
		aliases := strings.Split(group, "|")
		for _, alias := range aliases {
			fields[compactField(alias)] = aliases[0]
		}
	}
	return fields
}
